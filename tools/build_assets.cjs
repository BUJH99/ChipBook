// Build every declared asset in memory; --check never rewrites runtime files.
'use strict';
const fs = require('node:fs');
const path = require('node:path');
const esbuild = require('esbuild');
const root = path.resolve(__dirname, '..');
const check = process.argv.includes('--check');
const manifest = JSON.parse(fs.readFileSync(path.join(root, 'src/app/asset-builds.json'), 'utf8'));

async function buildAssets({ repoRoot = root, config = manifest, checkOnly = false, log = console.log } = {}) {
    const outputs = [];
    for (const bundle of config.bundles) {
        const outputPath = path.resolve(repoRoot, bundle.output);
        const assetsRoot = path.join(repoRoot, 'assets') + path.sep;
        if (!outputPath.startsWith(assetsRoot)) throw new Error('Bundle output must stay inside assets/');
        const css = bundle.output.endsWith('.css');
        const result = await esbuild.build({
            absWorkingDir: repoRoot,
            entryPoints: [bundle.entry],
            outfile: bundle.output,
            bundle: true,
            write: false,
            logLevel: 'silent',
            charset: 'utf8',
            target: ['es2022'],
            ...(css ? {} : { format: 'iife', globalName: bundle.globalName }),
            minify: Boolean(bundle.minify),
            legalComments: 'inline',
            banner: css
                ? { css: '/* Generated by tools/build_assets.cjs; edit the declared source modules. */' }
                : { js: '// Generated by tools/build_assets.cjs; edit the declared source modules.' },
        });
        const content = result.outputFiles[0].contents;
        const current = fs.existsSync(outputPath) ? fs.readFileSync(outputPath) : null;
        const changed = !current || !current.equals(Buffer.from(content));
        outputs.push({ outputPath, content, changed, name: bundle.output });
    }
    // No bundle is written unless all entries compiled successfully.
    for (const item of outputs) {
        if (item.changed && !checkOnly) {
            fs.mkdirSync(path.dirname(item.outputPath), { recursive: true });
            fs.writeFileSync(item.outputPath, item.content);
        }
        log(`[${item.changed ? 'changed' : 'ok'}] ${item.name}`);
    }
    return !checkOnly || !outputs.some(item => item.changed);
}
module.exports = { buildAssets };
if (require.main === module) {
    buildAssets({ checkOnly: check }).then(ok => {
        if (!ok) { console.error('Generated assets are stale. Run python tools/dev.py build.'); process.exitCode = 1; }
    })
        .catch(error => { console.error(error.message); process.exitCode = 1; });
}
