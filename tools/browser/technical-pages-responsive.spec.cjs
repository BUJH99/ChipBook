const {test,expect}=require('@playwright/test');
const {openBook,openChapter,openSection}=require('./helpers.cjs');

test('technical interface figures, calculations and section navigation remain usable',async({page},info)=>{
    test.setTimeout(180000);
    const errors=await openBook(page,info),frame=await openChapter(page,9);
    const keys=['interface-boundary','io-electrical','gpio-uart','spi-qspi','i2c-i3c','ddr-lpddr','pcie','usb-typec-pd','ethernet','mipi','can-lin','serdes-phy','si-pi-channel','interface-budget','interface-debug'];
    for(let i=0;i<keys.length;i++){
        await openSection(page,keys[i]);const section=frame.locator(`[data-lesson-id="09.${String(i+1).padStart(2,'0')}"]`);
        await expect(section).toHaveClass(/technical-section/);
        await expect(section.locator('svg').first()).toBeVisible();
        expect(await section.locator('svg').evaluateAll(nodes=>nodes.every(node=>!/(?:NaN|undefined|Infinity)/.test(node.outerHTML)))).toBe(true);
        for(const image of await section.locator('img').all()){
            await image.scrollIntoViewIfNeeded();
            await expect.poll(()=>image.evaluate(node=>node.complete&&node.naturalWidth>0)).toBe(true);
        }
        await expect(section.getByRole('button',{name:'동작 재생',exact:true})).toHaveCount(0);
        await page.evaluate(()=>scrollTo(0,0));
        expect(await frame.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBe(true);
        await page.screenshot({path:info.outputPath(`section-09-${String(i+1).padStart(2,'0')}.png`),fullPage:true});
    }
    await openSection(page,'io-electrical');
    await frame.locator('[data-io-inputs] [name="resistance"]').fill('4400');
    await expect(frame.locator('[data-io-results]')).toContainText('440 ns');
    await expect(frame.locator('[data-io-current]')).toHaveText('0.75 mA');
    await openSection(page,'gpio-uart');
    await frame.getByLabel('송신 byte',{exact:true}).fill('150');
    await frame.getByLabel('Parity',{exact:true}).selectOption('even');
    await expect(frame.locator('[data-uart-summary]')).toContainText('0x96');
    await expect(frame.locator('[data-uart-summary]')).toContainText('Parity(1)');
    await openSection(page,'spi-qspi');
    await expect(frame.locator('[data-qspi-result]')).toContainText('560 ns');
    await frame.getByLabel('Payload byte',{exact:true}).fill('8');
    await expect(frame.locator('[data-qspi-result]')).toContainText('720 ns');
    await openSection(page,'ddr-lpddr');
    await frame.getByLabel('DQS delay tap',{exact:true}).fill('0');
    await expect(frame.locator('[data-ddr-training]')).toContainText('현재 FAIL');
    await frame.getByLabel('DQS delay tap',{exact:true}).fill('16');
    await expect(frame.locator('[data-ddr-training]')).toContainText('현재 PASS');
    await openSection(page,'usb-typec-pd');
    await frame.getByLabel('Type-C 연결 방향',{exact:true}).selectOption('CC2');
    await expect(frame.locator('[data-usb-path]')).toContainText('CC2');
    await openSection(page,'ethernet');
    await frame.getByLabel('Ethernet Payload byte',{exact:true}).fill('64');
    await expect(frame.locator('[data-ethernet-result]')).toContainText('816 ns');
    await frame.getByLabel('처리 frame',{exact:true}).fill('100');
    await expect(frame.locator('[data-ethernet-queue]')).toContainText('누적 drop 0');
    await openSection(page,'mipi');await frame.getByLabel('Bit per pixel',{exact:true}).fill('24');
    await expect(frame.locator('[data-mipi-result]')).toContainText('2.986 Gb/s');
    await openSection(page,'can-lin');await expect(frame.locator('[data-can-arbitration]')).toContainText('첫 차이 bit 4');
    await openSection(page,'si-pi-channel');await frame.getByLabel('부하 임피던스',{exact:true}).fill('50');
    await expect(frame.locator('[data-reflection-value]')).toContainText('ΓL = (ZL − Z₀) / (ZL + Z₀)0');
    await openSection(page,'interface-budget');await expect(frame.locator('[data-budget-serialization]')).toContainText('1.28 µs');
    await expect(frame.locator('[data-interface-budget-table] tbody tr')).toHaveCount(6);
    const bytes=await frame.locator('[data-interface-budget-table] tbody td:nth-child(3)').allTextContents();expect(bytes).toEqual(Array(6).fill('4096 B'));
    await openSection(page,'interface-debug');await frame.getByLabel('디버그 시나리오',{exact:true}).selectOption('stuck');
    await expect(frame.locator('[data-debug-evidence]')).toContainText('SDA stuck LOW');
    await frame.getByLabel('디버그 시나리오',{exact:true}).selectOption('read');
    await expect(frame.locator('[data-debug-evidence]')).toContainText('0xFF');
    expect(errors).toEqual([]);
});

test('I2C technical page keeps transactions, address bytes and wired-AND levels coherent',async({page},info)=>{
    const errors=await openBook(page,info),frame=await openChapter(page,9);
    await openSection(page,'i2c-i3c');
    const section=frame.locator('[data-lesson-id="09.05"]');
    await expect(section.locator('[data-i2c-ownership]')).toContainText('0xA0 → Target ACK');
    await expect(section.locator('[data-i2c-ownership]')).toContainText('0x3C → Controller NACK');
    await expect(section.locator('[data-visual-scene], [data-lab-action="play"], [data-lab-action="step"]')).toHaveCount(0);
    await section.getByLabel('7-bit 주소',{exact:true}).selectOption('104');
    await section.getByLabel('전송 방향',{exact:true}).selectOption('1');
    await expect(section.locator('[data-i2c-byte]')).toHaveText('0xD1');
    await expect(section.locator('[data-i2c-wave]')).toContainText('0xD1');
    await section.getByLabel('7-bit 주소',{exact:true}).selectOption('custom');
    await section.getByLabel('직접 주소 (10진)',{exact:true}).fill('42');
    await expect(section.locator('[data-i2c-byte]')).toHaveText('0x55');
    await expect(section.locator('[data-i2c-wave]')).toContainText('0x55');
    await section.getByLabel('7-bit 주소',{exact:true}).selectOption('104');
    await section.getByLabel('Transaction',{exact:true}).selectOption('nack');
    await expect(section.locator('[data-i2c-ownership]')).toContainText('0xD0 → Target NACK');
    await expect(section.locator('[data-i2c-ownership] tbody tr')).toHaveCount(2);
    await section.getByLabel('Transaction',{exact:true}).selectOption('read');
    await section.getByLabel('읽은 byte',{exact:true}).fill('90');
    await expect(section.locator('[data-i2c-ownership]')).toContainText('0x5A → Controller NACK');
    await section.locator('[name="targetSda"]').selectOption('1');
    await expect(section.locator('[data-i2c-electrical-view]')).toContainText('SDA : High');
    await section.locator('[name="controllerScl"]').selectOption('0');
    await expect(section.locator('[data-i2c-electrical-view]')).toContainText('SCL : Low');
    await expect(section.locator('[data-i2c-electrical-view]')).toContainText('SDA : High');
    expect(await section.locator('img').evaluateAll(imgs=>imgs.every(img=>img.complete&&img.naturalWidth>0))).toBe(true);
    expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBe(true);
    expect(await frame.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBe(true);
    await page.evaluate(()=>scrollTo(0,0));
    await page.screenshot({path:info.outputPath('i2c-interaction.png'),fullPage:true});
    await section.getByLabel('7-bit 주소',{exact:true}).selectOption('80');
    await section.getByLabel('전송 방향',{exact:true}).selectOption('0');
    await section.getByLabel('읽은 byte',{exact:true}).fill('60');
    await section.locator('[name="targetSda"]').selectOption('0');
    await section.locator('[name="controllerScl"]').selectOption('1');
    await page.evaluate(()=>scrollTo(0,0));
    await page.screenshot({path:info.outputPath('i2c-default.png'),fullPage:true});
    await openSection(page,'spi-qspi');
    await expect(frame.locator('[data-lesson-panel="spi-qspi"]')).toBeVisible();
    await openSection(page,'i2c-i3c');
    await expect(section.locator('[data-i2c-byte]')).toHaveText('0xA0');
    expect(errors).toEqual([]);
});
